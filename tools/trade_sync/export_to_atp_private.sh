#!/usr/bin/env bash
# scripts/export_to_atp_private.sh — owner order M65 X-5: re-sync Trade's engine into the PRIVATE repo atp-private for one tag.
#   1. exports the tagged commit (git archive — never the working tree) into a temp folder;
#   2. copies the PORT set into <atp-private checkout>/atp_private/trade_engine/<original paths> with only the import paths rewritten
#      (scripts/atp_import_rewrite.py), plus the covering tests, docs/knowledge, the pack builder, a README and tools/trade_sync/;
#   3. in that checkout: switches to branch import/<tag> (works on an empty repo: the first commit) and commits the copy — never pushes;
#   4. regenerates the parity fixtures for the tag (scripts/export_parity_fixtures.py, run from a temporary worktree AT the tag) into
#      <trade-data>/parity/<tag> (refused by that script if the folder exists — a fixture set is never overwritten).
# No data files, no secrets, no VPS paths; nothing on any VPS; no network (the push is the owner's / session's own step).
#
#   scripts/export_to_atp_private.sh <tag> [atp-private checkout, default /home/user/atp-private]
#       [--ref <commit>]        build from this commit instead of the tag (dry run before the tag exists; README / commit say so)
#       [--no-fixtures]         skip step 4      [--no-commit]   skip step 3 (copy only)
#       [--trade-data <dir>]    default: $TRADE_DATA_DIR or /home/user/trade-data
set -euo pipefail

TAG="${1:?usage: export_to_atp_private.sh <tag> [atp-private checkout] [--ref <commit>] [--no-fixtures] [--no-commit] [--trade-data <dir>]}"
shift
DEST="/home/user/atp-private"
if [[ $# -gt 0 && "$1" != --* ]]; then DEST="$1"; shift; fi
REF="" FIXTURES=1 COMMIT=1 TD="${TRADE_DATA_DIR:-/home/user/trade-data}"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --ref) REF="$2"; shift 2 ;;
    --no-fixtures) FIXTURES=0; shift ;;
    --no-commit) COMMIT=0; shift ;;
    --trade-data) TD="$2"; shift 2 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
if [[ -z "$REF" ]]; then
  git -C "$REPO" rev-parse -q --verify "refs/tags/$TAG" >/dev/null || { echo "tag $TAG not found (create it on the merge commit, or --ref for a dry run)" >&2; exit 1; }
  REF="$TAG"
fi
SHA="$(git -C "$REPO" rev-parse "$REF^{commit}")"
mkdir -p "$DEST"
DEST="$(cd "$DEST" && pwd)"
case "$DEST/" in "$REPO"/*) echo "the target is inside this repo — atp-private is a separate checkout" >&2; exit 1 ;; esac

SRC="$(mktemp -d)"
trap 'rm -rf "$SRC"' EXIT
git -C "$REPO" archive "$SHA" | tar -x -C "$SRC"
echo "source: $REF ($SHA) → $SRC"

# the rewrite runs from the EXPORTED tree (its own engine_closure / classification = the tag's)
python3 "$SRC/scripts/atp_import_rewrite.py" --src "$SRC" --dest "$DEST" --tag "$TAG" --commit "$SHA"

if [[ "$COMMIT" == 1 ]]; then
  if [[ ! -d "$DEST/.git" ]]; then
    git -C "$DEST" init -q
  fi
  BR="import/$TAG"
  if git -C "$DEST" rev-parse -q --verify "refs/heads/$BR" >/dev/null; then
    git -C "$DEST" checkout -q "$BR"
  else
    git -C "$DEST" checkout -q -b "$BR"                                   # also on an empty repo (unborn branch ⇒ the first commit)
  fi
  git -C "$DEST" add -A atp_private tools/trade_sync
  if git -C "$DEST" diff --cached --quiet; then
    echo "atp-private: nothing changed on $BR"
  else
    MSG="Import Trade engine $TAG ($SHA) into atp_private/trade_engine"
    [[ "$REF" != "$TAG" ]] && MSG="$MSG [built from --ref $REF; the tag is created later]"
    git -C "$DEST" commit -q -m "$MSG" -m "Generated by Trade scripts/export_to_atp_private.sh: code as is, import paths rewritten (tools/trade_sync/atp_import_rewrite.py). PAPER only; no data, no secrets."
    echo "atp-private: committed on $BR: $(git -C "$DEST" rev-parse --short HEAD) (not pushed)"
  fi
fi

if [[ "$FIXTURES" == 1 ]]; then
  WT="$(mktemp -d)"
  git -C "$REPO" worktree add -q --detach "$WT" "$SHA"
  ( cd "$WT" && TRADE_DATA_DIR="$TD" python3 scripts/export_parity_fixtures.py --tag "$TAG" --out "$TD/parity/$TAG" ) || { git -C "$REPO" worktree remove --force "$WT"; exit 1; }
  git -C "$REPO" worktree remove --force "$WT"
  echo "fixtures: $TD/parity/$TAG"
fi
